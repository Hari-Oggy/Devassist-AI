"""
AgenticExecutor — AI-generated analysis scripts executed in a secure sandbox.

What this does
--------------
During a code review, an LLM can generate a short Python *analysis script*
tailored to the specific PR — for example:

    - Run the changed module's own test suite to detect regressions.
    - Parse a config file introduced in the PR and validate its schema.
    - Import a Python module from the PR and call a function with safe inputs
      to verify it doesn't raise unexpectedly.

These scripts are then executed **inside a :class:`DockerSandbox`** container
so that malicious or buggy code can never affect the host.

Security model
--------------
1. Script is generated by the LLM from a restricted prompt (no networking).
2. Script is written to a temp file that is mounted **read-only** in the
   container at ``/sandbox/script.py``.
3. The container has **no network** access, a **read-only** repo mount, and
   runs as ``nobody`` with all Linux capabilities dropped.
4. A strict wall-clock timeout kills the container if the script hangs.
5. The container is unconditionally destroyed after each run.

Usage
-----
    executor = AgenticExecutor(sandbox=DockerSandbox())
    result = executor.execute_analysis(
        pr_diff="...",
        repo_path="/path/to/repo",
        pr_number=42,
    )
    print(result.findings_summary)
"""

